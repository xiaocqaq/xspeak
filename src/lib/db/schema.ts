/**
 * dictionary：离线词典（ECDICT）。
 *
 * 为什么和 words 分开而不是合成一张表：
 * - words 是“你在学的词”，百到千量级，带主题、来源、例句，跟 user_words 关联；
 * - dictionary 是“查得到的词”，十万到百万量级，只用于查询。
 * 掘在一起的话，每次拉“今天要学的词”都要在百万行里扭，而且 source 字段
 * 会变成一个既要区分“学习来源”又要区分“是否词典条目”的缝合字段。
 *
 * translation 存 ECDICT 原始的多行中文释义（\n 分隔），definition 存英文释义。
 * frq 是词频排名（越小越常用）0 表示未知；tag 是考纲标签（zk/gk/cet4...）。
 */
DDL.push(`CREATE TABLE IF NOT EXISTS dictionary (
  word TEXT PRIMARY KEY,
  phonetic TEXT,
  definition TEXT,
  translation TEXT,
  pos TEXT,
  collins SMALLINT,
  oxford SMALLINT,
  tag TEXT,
  bnc INTEGER,
  frq INTEGER,
  exchange TEXT,
  detail TEXT,
  audio TEXT
)`);

// 查词走小写匹配（用户选中的词可能带大写或变形）
DDL.push(`CREATE INDEX IF NOT EXISTS idx_dict_word_lower ON dictionary(lower(word))`);
// 按词频挑“值得学的词”时用
DDL.push(`CREATE INDEX IF NOT EXISTS idx_dict_frq ON dictionary(frq) WHERE frq > 0`);

/**
 * word_level：单词的 CEFR 等级（CEFR-J + Octanove，人工标注）。
 *
 * 为什么不复用 dictionary.tag：tag 是考纲收录信息（zk/gk/cet4/cet6/ky/toefl/ielts/gre），
 * 只能当分级的代理，一个词进了 cet4 大纲不等于它就是 B1。实测两者只有 54% 对得上。
 * ECDICT 里也没有 CEFR 列，所以等级只能另存一张表，用 word 关联。
 *
 * 分工是刻意的：这张表只管"这个词是几级"，中文释义、音标、词频仍然全部来自
 * dictionary —— CEFR-J 两份表都不带中文和音标，单独用不了。8493 个词里
 * 8418（99.1%）能 join 上，其中 8115 同时有中文和音标。
 *
 * 表是空的时候选词会自动退回 tag 方案（见 repo/dictionary.ts），
 * 所以先部署后导入不会让新词环节失效。
 *
 * 数据来源和授权见 scripts/import-levels.mjs 顶部。
 */
DDL.push(`CREATE TABLE IF NOT EXISTS word_level (
  word TEXT PRIMARY KEY,
  cefr TEXT NOT NULL,
  -- 词性，CEFR-J 原始标注（noun/verb/adjective…）。同词多词性时取最低那级，这里存对应的词性
  pos TEXT,
  -- 数据来源：cefrj（A1-B2）或 octanove（C1-C2），出问题时能追到是哪份表标的
  src TEXT NOT NULL DEFAULT 'cefrj'
)`);

// 按等级取词是选词的主查询路径
DDL.push(`CREATE INDEX IF NOT EXISTS idx_word_level_cefr ON word_level(cefr)`);

