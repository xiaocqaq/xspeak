DDL.push(`ALTER TABLE users ADD COLUMN IF NOT EXISTS external_username TEXT`);
DDL.push(`ALTER TABLE users ADD COLUMN IF NOT EXISTS external_email TEXT`);
DDL.push(
  `CREATE UNIQUE INDEX IF NOT EXISTS idx_users_external ON users(external_id) WHERE external_id IS NOT NULL`,
);

/*
 * 老库的 users.id 是光秃秃的 INTEGER PRIMARY KEY —— 没有序列，靠代码写死 1。
 * 多人之后必须让它自己发号，否则第二个人注册时 INSERT 不给 id 会直接违反非空约束。
 *
 * 上面的 CREATE TABLE 已经带 GENERATED BY DEFAULT AS IDENTITY，但那句对已存在的
 * 库是空操作，所以老库得单独补。ADD GENERATED 不支持 IF NOT EXISTS，重复执行会
 * 报 55006，用 DO 块吞掉；同时把序列的起点推到当前最大 id 之后，
 * 不然第一次自动发号会撞上历史那条 id=1。
 */
DDL.push(`DO $$
BEGIN
  BEGIN
    ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  EXCEPTION
    WHEN others THEN NULL;  -- 已经是 identity 了
  END;
  PERFORM setval(
    pg_get_serial_sequence('users', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 0) FROM users), 1)
  );
EXCEPTION
  WHEN others THEN NULL;  -- 没有序列（极老的库且 ADD GENERATED 失败），留给下次
END $$`);

