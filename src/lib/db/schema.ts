/*
 * 一人一份档案。身份来自上游 ai.xlingo.fun（见 src/lib/auth/config.mjs），
 * 这里只存「上游那个人 ↔ 本地这份档案」的对应关系：
 *
 *   external_id  上游的用户数字 id，存成 TEXT 避免以后上游换成 uuid 要改类型
 *   external_username / external_email  只为了显示和排查，不参与关联
 *
 * external_id 为 NULL 的那条是单人模式留下的历史档案（id=1）。
 * 唯一索引用 partial index：NULL 在 UNIQUE 里本来就互不冲突，但写清楚更保险。
 */
