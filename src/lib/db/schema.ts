// 上面那句是 CREATE TABLE IF NOT EXISTS —— 对已存在的库它什么都不做。
// 新增列必须另写幂等 ALTER，否则老库升级后会在读这些列时直接报错。
//
// voice 和 ai_voice 是两回事，别弄混：
// - voice：浏览器 Web Speech 的语音包名字，给逐句朗读用，离线可用
// - ai_voice：StepFun realtime 的音色 id，给畅聊用，两边名字不通用
/*
 * new_words_per_day 的默认值从 8 提到 10。CREATE TABLE 只对新库生效，
 * 这句把老库里还停在旧默认 8 的档案也顺手抬上来 —— 用户自己调到别的值的不动。
 * 上限 100：设置页滑杆和 API 校验都按这个口径。
 */
DDL.push(`DO $$
BEGIN
  UPDATE users SET new_words_per_day = 10 WHERE new_words_per_day = 8;
END $$`);

